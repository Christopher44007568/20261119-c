#include "mesh.h"
#include <cstdio>
#include <fstream>

// Emits the test mesh as a JSON document consumed by the WebGL2 viewer,
// including the CPU reference tangent frames and per-face chirality.
int main(int argc, char** argv) {
    const char* out = argc > 1 ? argv[1] : "viewer/mesh_data.js";
    Mesh mesh = buildTestMesh(4);

    std::ofstream f(out);
    if (!f) { std::perror(out); return 1; }

    f << "// Auto-generated by src/export_mesh.cpp - do not edit.\n";
    f << "window.MESH_DATA = {\n  vertices: [\n";
    for (size_t i = 0; i < mesh.verts.size(); ++i) {
        const Vertex& v = mesh.verts[i];
        const TangentFrame& fr = mesh.frames[i];
        f << "    ["
          << v.pos.x << "," << v.pos.y << "," << v.pos.z << ","
          << v.normal.x << "," << v.normal.y << "," << v.normal.z << ","
          << v.uv.x << "," << v.uv.y << ","
          << fr.T.x << "," << fr.T.y << "," << fr.T.z << ","
          << fr.N.x << "," << fr.N.y << "," << fr.N.z << ","
          << fr.handedness << "," << (fr.degenerate ? 1 : 0)
          << "],\n";
    }
    f << "  ],\n  indices: [\n";
    for (size_t i = 0; i < mesh.tris.size(); ++i) {
        const Triangle& t = mesh.tris[i];
        f << "    " << t.v[0] << "," << t.v[1] << "," << t.v[2] << ","
          << " // face " << i << " sign " << mesh.faceSign[i] << "\n";
    }
    f << "  ],\n  faceSign: [";
    for (size_t i = 0; i < mesh.faceSign.size(); ++i) {
        f << (i ? "," : "") << mesh.faceSign[i];
    }
    f << "],\n  degenerateNormal: ["
      << mesh.degenerateNormal.x << "," << mesh.degenerateNormal.y
      << "," << mesh.degenerateNormal.z << "]\n};\n";

    std::printf("wrote %zu verts, %zu tris to %s\n",
                mesh.verts.size(), mesh.tris.size(), out);
    return 0;
}
